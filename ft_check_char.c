#include "ft_printf.h"

int	ft_check_char(const char *p)
{
	if (*p != '%')
		return (0);
	p++;
	// if (*p == '%')
	// 	return (2);
	if ((*p >= 'a' && *p <= 'z')
		|| (*p >= 'A' && *p < 'Z') || *p)
		return (1);
	return (-1);
}
