#include "ft_printf.h"

int	ft_check_char(void *p)
{
	unsigned char	*s;

	s = p;
	if (*s != '%')
		return (0);
	s++;
	if (*s == '%')
		return (2);
	if ((*s >= 'a' && *s <= 'z')
		|| (*s >= 'A' && *s < 'Z'))
		return (1);
	return (-1);
}
